/**
 * Writes the aggregate's `dist/pre-upgrade.css`: a `display` rule for each
 * shadow-DOM element while it is still undefined.
 *
 * A custom element renders as `display: inline` until its definition loads,
 * and a server-rendered page shows that state until the client registers the
 * elements. A host whose shadow styles make it a block, grid, or flex box then
 * jumps on upgrade. This file gives every such host its upgraded `display`
 * ahead of time. It reads that value from each element's own `:host` rule, so
 * it cannot drift from the component styles.
 *
 * Run from the aggregate package directory after every component has built.
 * Light-DOM components need nothing here: their static `base.css` already
 * carries their layout.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

/** The `display` value of a stylesheet's unconditional `:host` rule, if it sets one. */
export function hostDisplay(cssText) {
  for (const match of cssText.matchAll(/(?:^|[}\s;]):host\s*\{([^}]*)\}/g)) {
    const display = /(?:^|;)\s*display\s*:\s*([^;!]+)/.exec(match[1]);

    if (display) {
      return display[1].trim();
    }
  }

  return undefined;
}

/**
 * Groups tags by display value into one `:not(:defined)` rule each. `none` is
 * left out on purpose: content stays visible until an element takes control.
 */
export function preUpgradeCss(displays) {
  const groups = new Map();

  for (const [tag, display] of [...displays].sort(([a], [b]) => a.localeCompare(b))) {
    if (display === 'inline' || display === 'none') {
      continue;
    }

    groups.set(display, [...(groups.get(display) ?? []), tag]);
  }

  const rules = [...groups]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([display, tags]) =>
        `  :is(${tags.join(', ')}):not(:defined) {\n    display: ${display};\n  }`,
    );

  return [
    '/*',
    ' * Generated by the rc-webcomponents build. Gives each shadow-DOM element the display it',
    ' * takes once defined, so a server-rendered page does not shift when the elements upgrade.',
    ' */',
    '@layer rc-base {',
    rules.join('\n\n'),
    '}',
    '',
  ].join('\n');
}

async function collectDisplays(packagesRoot) {
  const displays = new Map();

  for (const entry of readdirSync(packagesRoot, { withFileTypes: true })) {
    if (!entry.isDirectory()) {
      continue;
    }

    const directory = join(packagesRoot, entry.name);
    const manifest = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'));
    let elements;

    try {
      elements = JSON.parse(readFileSync(join(directory, 'dist/custom-elements.json'), 'utf8'));
    } catch {
      continue;
    }

    const declarations = elements.modules
      .flatMap((module) => module.declarations ?? [])
      .filter((declaration) => declaration.customElement && declaration.tagName);

    if (declarations.length === 0 || !manifest.exports?.['.']) {
      continue;
    }

    const module = await import(manifest.name);

    for (const { name, tagName } of declarations) {
      const element = module[name];

      element?.finalize?.();

      const styles = (element?.elementStyles ?? []).map((style) => style.cssText ?? '').join('\n');
      const display = hostDisplay(styles);

      if (display) {
        displays.set(tagName, display);
      }
    }
  }

  return displays;
}

async function main() {
  const packagesRoot = resolve(process.cwd(), '..');
  const displays = await collectDisplays(packagesRoot);

  writeFileSync(join(process.cwd(), 'dist/pre-upgrade.css'), preUpgradeCss(displays));
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
