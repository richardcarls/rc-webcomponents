/**
 * Generates the aggregate's React and Solid JSX typings from the Custom
 * Elements Manifest (`yarn cem:analyze` writes `dist/custom-elements.json`).
 *
 * The typings reference each element's real class and the global
 * `HTMLElementEventMap`, so prop and event types come from the component
 * source instead of a hand-maintained copy. The manifest only decides which
 * tags, attributes, properties, events, and CSS custom properties exist.
 *
 *   node scripts/generate-framework-typings.mjs          write the files
 *   node scripts/generate-framework-typings.mjs --check  fail if they are stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = join(ROOT, 'dist', 'custom-elements.json');
const OUTPUT = join(ROOT, 'packages', 'rc-webcomponents', 'src');

const EVENT_NAME = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)+$/;

/** Every custom element declaration in the manifest, with the package that exports it. */
export function collectElements(manifest) {
  const elements = [];

  for (const module of manifest.modules ?? []) {
    const match = /^packages\/([^/]+)\/src\//.exec(module.path);

    if (!match) {
      continue;
    }

    for (const declaration of module.declarations ?? []) {
      if (!declaration.customElement || !declaration.tagName) {
        continue;
      }

      elements.push(describeElement(declaration, `@rcarls/${match[1]}`));
    }
  }

  return elements.sort((a, b) => a.tag.localeCompare(b.tag));
}

function describeElement(declaration, packageName) {
  const writableFields = (declaration.members ?? []).filter(
    (member) =>
      member.kind === 'field' &&
      !member.static &&
      !member.readonly &&
      (member.privacy ?? 'public') === 'public' &&
      !member.name.startsWith('_'),
  );
  const fieldNames = new Set(writableFields.map((field) => field.name));
  // Plain accessors and @attr-only attributes carry no fieldName, so fall back
  // to the camelCased attribute name. An attribute with no writable property
  // behind it at all is typed as a plain string.
  const fieldFor = (attribute) =>
    [attribute.fieldName, camelCase(attribute.name)].find((name) => name && fieldNames.has(name));
  const attributes = (declaration.attributes ?? []).map((attribute) => ({
    name: attribute.name,
    field: fieldFor(attribute),
  }));
  const events = [
    ...new Set(
      (declaration.events ?? []).map((event) => event.name).filter((name) => EVENT_NAME.test(name)),
    ),
  ].sort();
  const cssProperties = [
    ...new Set((declaration.cssProperties ?? []).map((property) => property.name)),
  ].sort();

  return {
    tag: declaration.tagName,
    className: declaration.name,
    packageName,
    attributes: uniqueBy(attributes, (attribute) => attribute.name),
    properties: [...fieldNames].sort(),
    events,
    cssProperties,
  };
}

const camelCase = (name) => name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

function uniqueBy(items, key) {
  const seen = new Map();

  for (const item of items) {
    seen.set(key(item), item);
  }

  return [...seen.values()].sort((a, b) => key(a).localeCompare(key(b)));
}

const quote = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`);

function header(framework, reference) {
  return `/**
 * ${framework} JSX typings for rc-webcomponents.
 *
 * Generated by \`yarn codegen:typings\` from the Custom Elements Manifest. Do
 * not edit by hand: change the component source and its JSDoc instead.
 *
 * Reference this file once in your project, for example in a global .d.ts:
 *
 *   /// <reference types="${reference}" />
 *
 * Element, event detail, and value types come from each component package.
 * Import them from there, such as \`import type { RCSelect } from '@rcarls/rc-select'\`.
 */
`;
}

function imports(elements) {
  const byPackage = new Map();

  for (const { packageName, className } of elements) {
    byPackage.set(packageName, [...(byPackage.get(packageName) ?? []), className]);
  }

  return [...byPackage]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([packageName, names]) =>
        `import type { ${[...new Set(names)].sort().join(', ')} } from '${packageName}';`,
    )
    .join('\n');
}

function eventUnion(events) {
  return events.length === 0 ? 'never' : events.map((event) => `'${event}'`).join(' | ');
}

function cssPropertyLines(elements) {
  const names = [...new Set(elements.flatMap((element) => element.cssProperties))].sort();

  return names.map((name) => `    '${name}'?: string | number;`).join('\n');
}

/** React 19 sets a prop as a property when the element has it, else as an attribute. */
export function reactTypings(elements) {
  const entries = elements.map((element) => {
    const own = [];

    for (const { name, field } of element.attributes) {
      if (!field) {
        own.push(`        ${quote(name)}?: string;`);
      } else if (name !== field) {
        own.push(`        ${quote(name)}?: RCAttribute<${element.className}['${field}']>;`);
      }
    }

    for (const field of element.properties) {
      own.push(`        ${quote(field)}?: ${element.className}['${field}'];`);
    }

    return `      '${element.tag}': RCElementProps<
        ${element.className},
        {
${own.join('\n')}
        },
        ${eventUnion(element.events)}
      >;`;
  });

  return `${header('React', '@rcarls/rc-webcomponents/react')}
import type * as React from 'react';

${imports(elements)}

/** Attribute values are strings, so a numeric attribute also takes a numeric string. */
type RCAttribute<Value> = Value extends number ? Value | \`\${number}\` : Value;

/** \`on<event-name>\` handlers, which React 19 attaches as listeners for that exact event. */
type RCEventProps<Events extends keyof HTMLElementEventMap> = {
  [Event in Events as \`on\${Event}\`]?: (event: HTMLElementEventMap[Event]) => void;
};

type RCElementProps<
  Element extends HTMLElement,
  Own extends object,
  Events extends keyof HTMLElementEventMap,
> = Omit<React.DetailedHTMLProps<React.HTMLAttributes<Element>, Element>, keyof Own> &
  Own &
  RCEventProps<Events>;

declare module 'react' {
  namespace JSX {
    interface IntrinsicElements {
${entries.join('\n\n')}
    }
  }

  /** The components' public CSS custom properties, for \`style\` objects. */
  interface CSSProperties {
${cssPropertyLines(elements)}
  }
}
`;
}

/** Solid sets attributes by default; \`prop:\` writes a property and \`on:\` adds a listener. */
export function solidTypings(elements) {
  const entries = elements.map((element) => {
    const own = [];

    for (const { name, field } of element.attributes) {
      own.push(
        field
          ? `        ${quote(name)}?: RCAttribute<${element.className}['${field}']>;`
          : `        ${quote(name)}?: string;`,
      );
    }

    for (const field of element.properties) {
      own.push(`        'prop:${field}'?: ${element.className}['${field}'];`);
    }

    return `      '${element.tag}': RCElementProps<
        ${element.className},
        {
${own.join('\n')}
        },
        ${eventUnion(element.events)}
      >;`;
  });

  return `${header('SolidJS', '@rcarls/rc-webcomponents/solid')}
import type { JSX } from 'solid-js';

${imports(elements)}

/**
 * Solid passes \`""\` for a boolean \`true\` attribute, and attribute values are
 * strings, so a numeric attribute also takes a numeric string.
 */
type RCAttribute<Value> = Value extends boolean
  ? boolean | ''
  : Value extends number
    ? Value | \`\${number}\`
    : Value;

type RCEventProps<Events extends keyof HTMLElementEventMap> = {
  [Event in Events as \`on:\${Event}\`]?: (event: HTMLElementEventMap[Event]) => void;
};

type RCElementProps<
  Element extends HTMLElement,
  Own extends object,
  Events extends keyof HTMLElementEventMap,
> = Omit<JSX.HTMLAttributes<Element>, keyof Own> & Own & RCEventProps<Events>;

declare module 'solid-js' {
  namespace JSX {
    interface IntrinsicElements {
${entries.join('\n\n')}
    }

    /** The components' public CSS custom properties, for \`style\` objects. */
    interface CSSProperties {
${cssPropertyLines(elements)}
    }
  }
}
`;
}

async function format(path, source) {
  const options = (await prettier.resolveConfig(path)) ?? {};

  return prettier.format(source, { ...options, filepath: path });
}

export async function generateFrameworkTypings({ check = false } = {}) {
  const elements = collectElements(JSON.parse(readFileSync(MANIFEST, 'utf8')));
  const files = new Map([
    [join(OUTPUT, 'react.d.ts'), reactTypings(elements)],
    [join(OUTPUT, 'solid.d.ts'), solidTypings(elements)],
  ]);
  const stale = [];

  for (const [path, source] of files) {
    const contents = await format(path, source);
    let current;

    try {
      current = readFileSync(path, 'utf8');
    } catch {
      current = undefined;
    }

    if (current !== contents) {
      stale.push(path);

      if (!check) {
        writeFileSync(path, contents);
      }
    }
  }

  return { elementCount: elements.length, stale };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const check = process.argv.includes('--check');
  const { elementCount, stale } = await generateFrameworkTypings({ check });

  if (check && stale.length > 0) {
    console.error(
      ['Framework typings are out of date. Run `yarn codegen:typings`.', ...stale].join('\n'),
    );

    process.exitCode = 1;
  } else {
    console.log(
      `Framework typings cover ${elementCount} elements (${stale.length} file(s) ${check ? 'stale' : 'written'}).`,
    );
  }
}
