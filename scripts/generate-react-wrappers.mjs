/**
 * Generates `@rcarls/rc-react`: one `@lit/react` wrapper module per component
 * package, plus the tag-to-definition map behind `<RcRegister>`.
 *
 * Wrappers are client components. Each module registers its elements when it
 * loads, and maps every documented custom event to a camelCased `on` prop.
 *
 *   node scripts/generate-react-wrappers.mjs          write the files
 *   node scripts/generate-react-wrappers.mjs --check  fail if they are stale
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

import { collectElements } from './generate-framework-typings.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = join(ROOT, 'dist', 'custom-elements.json');
const PACKAGE_ROOT = join(ROOT, 'packages', 'rc-react');
const GENERATED = join(PACKAGE_ROOT, 'src', 'components');
const LOADERS = join(PACKAGE_ROOT, 'src', 'loaders.ts');
const MANIFEST_PATH = join(PACKAGE_ROOT, 'package.json');

const pascalCase = (name) =>
  name.replace(/(^|-)([a-z0-9])/g, (_, __, letter) => letter.toUpperCase());

/** `rc-select` becomes `RcSelect`; `rc-select-change` becomes `onRcSelectChange`. */
export const componentName = (tag) => pascalCase(tag);
export const eventProp = (event) => `on${pascalCase(event)}`;

const directoryOf = (packageName) => packageName.replace('@rcarls/', '');

export function groupByPackage(elements) {
  const groups = new Map();

  for (const element of elements) {
    const directory = directoryOf(element.packageName);

    groups.set(directory, [...(groups.get(directory) ?? []), element]);
  }

  return new Map([...groups].sort(([a], [b]) => a.localeCompare(b)));
}

/** One wrapper module for every element a component package defines. */
export function wrapperModule(directory, elements) {
  const classImports = elements
    .map((element) => `${element.className} as ${element.className}Element`)
    .join(', ');
  const wrappers = elements.map((element) => {
    const events = element.events
      .map(
        (event) =>
          `    ${eventProp(event)}: '${event}' as EventName<HTMLElementEventMap['${event}']>,`,
      )
      .join('\n');
    const eventMap = events ? `\n  events: {\n${events}\n  },` : '';

    return `/** React wrapper for \`<${element.tag}>\`. Registers the element when this module loads. */
export const ${componentName(element.tag)} = createComponent({
  tagName: '${element.tag}',
  elementClass: ${element.className}Element,
  react: React,
  displayName: '${componentName(element.tag)}',${eventMap}
});`;
  });
  const hasEvents = elements.some((element) => element.events.length > 0);

  return `'use client';

// Generated by \`yarn codegen:react\`. Do not edit by hand.
import { createComponent${hasEvents ? ', type EventName' : ''} } from '@lit/react';
// The default export, not a namespace: @lit-labs/ssr-react patches
// React.createElement on it, which a namespace import would not see.
import React from 'react';

import { ${classImports} } from '@rcarls/rc-webcomponents/${directory}';
import '@rcarls/rc-webcomponents/${directory}/define';

${wrappers.join('\n\n')}
`;
}

/** Literal dynamic imports, so bundlers split each definition into its own chunk. */
export function loadersModule(groups) {
  const entries = [...groups].flatMap(([directory, elements]) =>
    elements.map(
      (element) =>
        `  '${element.tag}': () => import('@rcarls/rc-webcomponents/${directory}/define'),`,
    ),
  );

  return `// Generated by \`yarn codegen:react\`. Do not edit by hand.

/** Loads the definition of each custom element by tag. */
export const elementLoaders = {
${entries.join('\n')}
} as const satisfies Record<string, () => Promise<unknown>>;

/** A custom element tag \`<RcRegister>\` can load. */
export type RcElementTag = keyof typeof elementLoaders;
`;
}

function packageExports(manifest, groups) {
  const exports = {};

  for (const [key, value] of Object.entries(manifest.exports ?? {})) {
    if (!/^\.\/rc-/.test(key)) {
      exports[key] = value;
    }
  }

  for (const directory of groups.keys()) {
    exports[`./${directory}`] = {
      import: {
        types: `./dist/types/components/${directory}.d.ts`,
        default: `./dist/components/${directory}.js`,
      },
    };
  }

  return { ...manifest, exports };
}

async function format(path, source) {
  const options = (await prettier.resolveConfig(path)) ?? {};

  return prettier.format(source, { ...options, filepath: path });
}

export async function generateReactWrappers({ check = false } = {}) {
  const groups = groupByPackage(collectElements(JSON.parse(readFileSync(MANIFEST, 'utf8'))));
  const files = new Map([[LOADERS, loadersModule(groups)]]);

  for (const [directory, elements] of groups) {
    files.set(join(GENERATED, `${directory}.ts`), wrapperModule(directory, elements));
  }

  const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'));

  files.set(MANIFEST_PATH, `${JSON.stringify(packageExports(manifest, groups), null, 2)}\n`);

  const stale = [];

  for (const [path, source] of files) {
    const contents = path.endsWith('.json') ? source : await format(path, source);
    const current = existsSync(path) ? readFileSync(path, 'utf8') : undefined;

    if (current !== contents) {
      stale.push(path);

      if (!check) {
        mkdirSync(dirname(path), { recursive: true });
        writeFileSync(path, contents);
      }
    }
  }

  const expected = new Set([...groups.keys()].map((directory) => `${directory}.ts`));

  for (const name of existsSync(GENERATED) ? readdirSync(GENERATED) : []) {
    if (!expected.has(name)) {
      stale.push(join(GENERATED, name));

      if (!check) {
        rmSync(join(GENERATED, name));
      }
    }
  }

  return { packageCount: groups.size, stale };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const check = process.argv.includes('--check');
  const { packageCount, stale } = await generateReactWrappers({ check });

  if (check && stale.length > 0) {
    console.error(
      ['React wrappers are out of date. Run `yarn codegen:react`.', ...stale].join('\n'),
    );

    process.exitCode = 1;
  } else {
    console.log(
      `React wrappers cover ${packageCount} packages (${stale.length} file(s) ${check ? 'stale' : 'written'}).`,
    );
  }
}
