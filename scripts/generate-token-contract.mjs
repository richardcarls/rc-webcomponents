/**
 * Generates the shared token outputs from the token contract in
 * `packages/rc-webcomponents/themes/token-contract.mjs`:
 *
 * - `packages/rc-common/src/tokenFallbacks.ts`: the fully expanded fallback of
 *   every shared token, read by `rcToken()` in component styles.
 * - `packages/rc-webcomponents/themes/base.css`: the optional base theme.
 * - The token table in `docs/docs/guide/styling.mdx`.
 *
 * Pass `--check` to report outputs that differ from the contract without
 * writing them.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

import { CSS_WIDE_KEYWORDS, syntaxError } from './css-syntax.mjs';

export { syntaxError } from './css-syntax.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CONTRACT_PATH = 'packages/rc-webcomponents/themes/token-contract.mjs';
const FALLBACKS_PATH = 'packages/rc-common/src/tokenFallbacks.ts';
const BASE_CSS_PATH = 'packages/rc-webcomponents/themes/base.css';
const DOCS_PATH = 'docs/docs/guide/styling.mdx';
const TABLE_START = '{/* token-table:start (generated by scripts/generate-token-contract.mjs) */}';
const TABLE_END = '{/* token-table:end */}';
const GENERATED_NOTICE = `Generated by scripts/generate-token-contract.mjs from ${CONTRACT_PATH}. Do not edit.`;

const TOKEN_REFERENCE = /var\((--rc-[a-z0-9-]+)\)/g;
const TOKEN_REFERENCE_TEST = /var\(--rc-[a-z0-9-]+\)/;

/** Checks the contract and returns a list of problems. */
export function validateContract({ groups, tokens }) {
  const problems = [];
  const groupIds = new Set(groups.map((group) => group.id));

  for (const [name, token] of Object.entries(tokens)) {
    if (!/^--rc-[a-z0-9-]+$/.test(name)) {
      problems.push(`${name}: name must match --rc-<name>`);
    }

    if (!groupIds.has(token.group)) {
      problems.push(`${name}: unknown group "${token.group}"`);
    }

    if (!token.description) {
      problems.push(`${name}: missing description`);
    }

    const error = syntaxError(token.syntax ?? '');

    if (error) {
      problems.push(`${name}: ${error}`);
    }

    if (token.default !== null && CSS_WIDE_KEYWORDS.has(token.default.trim())) {
      problems.push(
        `${name}: a CSS-wide keyword default applies to the custom property itself; use null`,
      );
    }

    for (const [, reference] of (token.default ?? '').matchAll(TOKEN_REFERENCE)) {
      if (!tokens[reference]) {
        problems.push(`${name}: default references unknown token ${reference}`);
      }
    }
  }

  for (const name of Object.keys(tokens)) {
    try {
      expandFallback(tokens, name);
    } catch (error) {
      problems.push(error.message);
    }
  }

  return problems;
}

/**
 * Expands a token's default so every referenced shared token carries its own
 * fallback: `var(--rc-surface)` becomes `var(--rc-surface, Canvas)`.
 */
export function expandFallback(tokens, name, seen = []) {
  if (seen.includes(name)) {
    throw new Error(`${[...seen, name].join(' -> ')}: cyclic default`);
  }

  const value = tokens[name].default;

  if (value === null) {
    return null;
  }

  return value.replace(TOKEN_REFERENCE, (_, reference) => {
    const fallback = expandFallback(tokens, reference, [...seen, name]);

    return fallback === null ? `var(${reference})` : `var(${reference}, ${fallback})`;
  });
}

function renderFallbacks(tokens) {
  const lines = Object.keys(tokens).map((name) => {
    const fallback = expandFallback(tokens, name);

    return `  '${name}': ${fallback === null ? 'null' : `'${fallback}'`},`;
  });

  return `// ${GENERATED_NOTICE}

/**
 * The fallback of every shared RC token, with referenced tokens expanded.
 * \`null\` marks a token that is unset by default.
 */
export const RC_TOKEN_FALLBACKS = {
${lines.join('\n')}
} as const;

/** The name of a shared RC token. */
export type RCTokenName = keyof typeof RC_TOKEN_FALLBACKS;
`;
}

/*
 * A derived default (one that reads another shared token) is left out of
 * base.css. Declared on :root it would resolve once and be inherited, so a
 * theme scoped to a class or shadow host that overrides only the referenced
 * token would not reach it. rcToken() expands the reference at each use site.
 */
function isDeclared(token) {
  return token.default !== null && !TOKEN_REFERENCE_TEST.test(token.default);
}

function renderBaseCss({ groups, tokens }) {
  const sections = groups
    .map((group) => {
      const declarations = Object.entries(tokens)
        .filter(([, token]) => token.group === group.id && isDeclared(token))
        .map(([name, token]) => `  ${name}: ${token.default};`);

      if (declarations.length === 0) {
        return null;
      }

      return [`  /* ${group.title} */`, ...declarations].join('\n');
    })
    .filter(Boolean);

  const conditional = new Map();

  for (const [name, token] of Object.entries(tokens)) {
    for (const { supports, value } of token.conditional ?? []) {
      conditional.set(supports, [...(conditional.get(supports) ?? []), `    ${name}: ${value};`]);
    }
  }

  const unset = Object.entries(tokens)
    .filter(([, token]) => token.default === null)
    .map(([name]) => name);
  const derived = Object.entries(tokens)
    .filter(([, token]) => token.default !== null && !isDeclared(token))
    .map(([name, token]) => `${name}: ${token.default}`);

  return `/*
 * ${GENERATED_NOTICE}
 *
 * Defines the rc-webcomponents semantic token set. Components carry the same
 * defaults as fallbacks, so this file is optional. Import it or override
 * these tokens at the application theme boundary.
 *
 * Left unset so components inherit the surrounding text style:
${unset.map((name) => ` * ${name}`).join('\n')}
 *
 * Derived from other tokens where components read them, so they follow a
 * scoped override of the token they reference. Set them here only to break
 * that link:
${derived.map((entry) => ` * ${entry}`).join('\n')}
 */
:root {
${sections.join('\n\n')}
}
${[...conditional]
  .map(
    ([supports, declarations]) =>
      `\n@supports ${supports} {\n  :root {\n${declarations.join('\n')}\n  }\n}\n`,
  )
  .join('')}`;
}

function renderDocsTable({ groups, tokens }) {
  const rows = groups.map((group) => {
    const entries = Object.entries(tokens).filter(([, token]) => token.group === group.id);
    const values = entries.filter(([, token]) => token.default !== null);
    const unset = entries.filter(([, token]) => token.default === null);
    const parts = [];

    if (values.length > 0) {
      parts.push(
        values
          .map(([name, token]) => {
            const conditional = (token.conditional ?? [])
              .map(({ value }) => ` (\`${value}\` when supported)`)
              .join('');

            return `\`${name}: ${token.default}\`${conditional}`;
          })
          .join('; '),
      );
    }

    if (unset.length > 0) {
      parts.push(`Unset: ${unset.map(([name]) => `\`${name}\``).join(', ')}.`);
    }

    if (group.note) {
      parts.push(group.note);
    }

    return `| ${group.title} | ${parts.join(' ')} |`;
  });

  return ['| Role | Tokens and defaults |', '| --- | --- |', ...rows].join('\n');
}

async function format(text, filepath) {
  const options = (await prettier.resolveConfig(filepath)) ?? {};

  return prettier.format(text, { ...options, filepath });
}

/** Builds every output from the contract and returns `{ path, current, expected }` entries. */
export async function generateTokenContract({ check = false } = {}) {
  const contract = await import(resolve(root, CONTRACT_PATH));
  const problems = validateContract(contract);

  if (problems.length > 0) {
    throw new Error(
      `Invalid token contract:\n${problems.map((problem) => `  ${problem}`).join('\n')}`,
    );
  }

  const docsPath = resolve(root, DOCS_PATH);
  const docs = readFileSync(docsPath, 'utf8');
  const start = docs.indexOf(TABLE_START);
  const end = docs.indexOf(TABLE_END);

  if (start === -1 || end === -1 || end < start) {
    throw new Error(`${DOCS_PATH}: missing token table markers`);
  }

  const outputs = [
    {
      path: FALLBACKS_PATH,
      expected: await format(renderFallbacks(contract.tokens), resolve(root, FALLBACKS_PATH)),
    },
    {
      path: BASE_CSS_PATH,
      expected: await format(renderBaseCss(contract), resolve(root, BASE_CSS_PATH)),
    },
    {
      path: DOCS_PATH,
      expected: await format(
        `${docs.slice(0, start + TABLE_START.length)}\n\n${renderDocsTable(contract)}\n\n${docs.slice(end)}`,
        docsPath,
      ),
    },
  ];

  const drift = [];

  for (const output of outputs) {
    const path = resolve(root, output.path);
    let current = '';

    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // A missing output counts as drift.
    }

    if (current !== output.expected) {
      drift.push(output.path);

      if (!check) {
        writeFileSync(path, output.expected);
      }
    }
  }

  return { drift, tokenCount: Object.keys(contract.tokens).length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const { drift, tokenCount } = await generateTokenContract({ check });

  if (check && drift.length > 0) {
    console.error(
      `Token contract outputs are out of date: ${drift.join(', ')}.\nRun \`node ${relative(process.cwd(), fileURLToPath(import.meta.url))}\`.`,
    );

    process.exitCode = 1;
  } else {
    console.log(
      `${check ? 'Checked' : 'Generated'} ${tokenCount} shared tokens${drift.length && !check ? ` (updated ${drift.join(', ')})` : ''}.`,
    );
  }
}
